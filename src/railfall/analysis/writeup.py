"""Write the results page (`docs/RESULTS.md`) from the weather results JSON.

    python -m railfall.analysis.writeup --stats weather-stats.json \\
        --report weather-report.json --charts docs/results/charts.json \\
        --out docs/RESULTS.md

The numbers in the write-up are never typed by hand: they come from the same
JSON the significance tests (`railfall.analysis.weather`) and the mart report
(`railfall.transform.report`) write, and the charts are linked only when the
`charts.json` manifest says they were drawn. The text is deterministic (no
date, stable ordering), so `--check` can fail CI when the committed page no
longer matches the JSON committed next to it.

Units: the tests report gaps as on-time *shares* (-0.0121); the page shows
percentage points (-1.21 pts), like the dashboards and the mart report.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

FACTORS = ("rain", "wind", "frost")
SEASON_ORDER = ("winter", "spring", "summer", "autumn")
GENERATED = (
    "<!-- Generated by `make results` from weather-stats.json and weather-report.json. "
    "Do not edit by hand: re-run the pipeline and regenerate. -->"
)
CAVEATS = (
    "Observational data: weather is not assigned at random, so a gap is an "
    "association within route x calendar-month strata, not a proven cause.",
    "Monthly aggregates: a storm on one day is diluted over the month, so effects of "
    "single severe events are understated.",
    "Weather is measured at the stations nearest each route's endpoints, not along "
    "the line; mid-route conditions are not observed.",
    "Punctuality is SNCF's published arrival punctuality per route and month; "
    "cancellations are outside the on-time share.",
)


def _pts(share: float | None, digits: int = 2) -> str:
    """An on-time share difference as signed percentage points."""
    return "n/a" if share is None else f"{share * 100:+.{digits}f} pts"


def _pct(share: float | None) -> str:
    return "n/a" if share is None else f"{share * 100:.1f}%"


def _p(value: float | None) -> str:
    if value is None:
        return "n/a"
    return "< 0.001" if value < 0.001 else f"{value:.3f}"


def _ci(row: Mapping[str, Any], digits: int = 2) -> str:
    low, high = row.get("ci_low"), row.get("ci_high")
    if low is None or high is None:
        return "n/a"
    return f"{low * 100:+.{digits}f} to {high * 100:+.{digits}f}"


def _table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return lines


def _ordered(rows: Sequence[Mapping[str, Any]], key: str = "factor") -> list[Mapping[str, Any]]:
    rank = {f: i for i, f in enumerate(FACTORS)}
    return sorted(rows, key=lambda r: rank.get(r.get(key, ""), len(FACTORS)))


def confounding_share(gap: float | None, naive: float | None) -> float | None:
    """Share of the naive pooled gap explained by route and month (0..1), if meaningful.

    Only defined when both gaps point the same way and the naive one is not zero:
    a sign flip means stratification changed the story, not that it trimmed it.
    """
    if gap is None or naive is None or naive == 0 or gap * naive < 0:
        return None
    return max(0.0, min(1.0, 1 - gap / naive))


def finding(test: Mapping[str, Any], alpha: float) -> str:
    """One bullet per factor: verdict, effect, CI, adjusted p, confounding."""
    factor = str(test["factor"]).capitalize()
    if test.get("verdict") == "not testable" or test.get("gap") is None:
        return f"- **{factor}: not testable** (no stratum had both adverse and normal months)."
    gap = test["gap"]
    if test.get("significant"):
        head = f"**{factor} {test['verdict']}**"
    else:
        head = f"**{factor}: no significant effect** at alpha = {alpha:g}"
    text = (
        f"- {head}: {_pts(gap)} on-time share (95% CI {_ci(test)}), "
        f"Holm-adjusted p = {_p(test.get('p_adjusted'))}, "
        f"{test.get('adverse_route_months', 0):,} adverse route-months."
    )
    share = confounding_share(gap, test.get("naive_gap"))
    if share is not None:
        text += (
            f" The naive pooled gap is {_pts(test['naive_gap'])}; comparing like with like "
            f"(same route, same calendar month) removes {share:.0%} of it."
        )
    elif test.get("naive_gap") is not None:
        text += f" The naive pooled gap was {_pts(test['naive_gap'])}."
    return text


def answer(tests: Sequence[Mapping[str, Any]]) -> str:
    """The one-sentence answer to the project's question."""
    if not tests:
        return "No significance tests in the input."
    hits = [t["factor"] for t in _ordered(tests) if t.get("significant")]
    rest = [t["factor"] for t in _ordered(tests) if not t.get("significant")]
    if not hits:
        return "**No**: none of the factors shows a significant effect after correction."
    verdict = "**Yes**" if not rest else "**Yes, partly**"
    verb = "lowers" if len(hits) == 1 else "lower"
    tail = "." if not rest else f"; {_join(rest)} {'does' if len(rest) == 1 else 'do'} not."
    return f"{verdict}: {_join(hits)} significantly {verb} punctuality{tail}"


def _join(words: Sequence[str]) -> str:
    return words[0] if len(words) == 1 else ", ".join(words[:-1]) + f" and {words[-1]}"


def _chart(charts: Mapping[str, Mapping[str, Any]], name: str, link: str) -> list[str]:
    chart = charts.get(name)
    if not chart:
        return []
    return [f"![{chart['title']}]({link}/{chart['file']})", ""]


def render(
    stats: Mapping[str, Any] | None,
    report: Mapping[str, Any] | None,
    charts: Sequence[Mapping[str, Any]] = (),
    chart_link: str = "results",
) -> str:
    """The whole results page as Markdown."""
    by_chart = {c["name"]: c for c in charts}
    out = [GENERATED, "", "# Results: does bad weather lower TGV punctuality?", ""]

    if stats:
        tests = _ordered(stats.get("tests") or [])
        alpha = float(stats.get("alpha", 0.05))
        first = tests[0] if tests else {}
        out += [
            answer(tests),
            "",
            f"Data: {stats.get('route_months', 0):,} route-months "
            f"({stats.get('routes', 0)} routes x {stats.get('months', 0)} months). "
            f"Each factor compares adverse and normal months *within* the same route and "
            f"calendar month; p-values come from {first.get('permutations', 0):,} "
            f"permutations and are Holm-adjusted across the three factors; confidence "
            f"intervals from {first.get('bootstrap', 0):,} bootstrap "
            f"resamples (seed {stats.get('seed', 'n/a')}).",
            "",
            "## Effect of each factor",
            "",
            *[finding(t, alpha) for t in tests],
            "",
            *_chart(by_chart, "effects", chart_link),
        ]
        seasons = stats.get("by_season") or []
        if seasons:
            rank = {s: i for i, s in enumerate(SEASON_ORDER)}
            frank = {f: i for i, f in enumerate(FACTORS)}
            seasons = sorted(
                seasons, key=lambda r: (rank.get(r["season"], 9), frank.get(r["factor"], 9))
            )
            tested = [r for r in seasons if r.get("tested")]
            out += ["## By season", ""]
            out += _table(
                ["Season", "Factor", "Gap", "95% CI (pts)", "Holm p", "Verdict"],
                [
                    [
                        r["season"],
                        r["factor"],
                        _pts(r.get("gap")),
                        _ci(r),
                        _p(r.get("p_adjusted")),
                        r.get("verdict", ""),
                    ]
                    for r in tested
                ],
            )
            untested = [f"{r['season']} {r['factor']}" for r in seasons if not r.get("tested")]
            if untested:
                out += ["", f"Not testable (no comparable months): {', '.join(untested)}."]
            out += ["", *_chart(by_chart, "seasons", chart_link)]
        dose = _ordered(stats.get("dose") or [])
        if dose:
            out += ["## Dose-response", ""]
            out += _table(
                ["Factor", "Slope per unit", "Unit", "95% CI (pts)", "Holm p", "Verdict", "Binary"],
                [
                    [
                        r["factor"],
                        _pts(r.get("slope"), 3),
                        r.get("unit", ""),
                        _ci(r, 3),
                        _p(r.get("p_adjusted")),
                        r.get("verdict", ""),
                        r.get("consistency", ""),
                    ]
                    for r in dose
                ],
            )
            out += [
                "",
                "*Binary* says whether the slope agrees with the binary test above "
                "(supported), points the other way (contradicted), or cannot be estimated.",
                "",
                *_chart(by_chart, "dose", chart_link),
            ]
        if stats.get("errors"):
            out += ["## Analysis errors", "", *[f"- {e}" for e in stats["errors"]], ""]

    if report:
        lines = report.get("headlines") or []
        intensity = report.get("intensity") or []
        if lines or intensity:
            out += ["## Descriptive view (marts, unadjusted)", ""]
            out += [f"- {line}" for line in lines]
            if lines:
                out.append("")
        if intensity:
            out += _table(
                ["Factor", "Band", "On time", "Gap vs baseline", "Route-months"],
                [
                    [
                        r["weather_factor"],
                        r["intensity_band"] + (" (baseline)" if r.get("is_baseline") else ""),
                        _pct(r.get("arrival_punctuality_rate")),
                        "-"
                        if r.get("punctuality_gap_pts") is None
                        else f"{r['punctuality_gap_pts']:+.1f} pts",
                        f"{r.get('route_months', 0):,}",
                    ]
                    for r in sorted(
                        intensity,
                        key=lambda r: (
                            FACTORS.index(r["weather_factor"])
                            if r["weather_factor"] in FACTORS
                            else 9,
                            r.get("band_order", 0),
                        ),
                    )
                ],
            )
            out += ["", *_chart(by_chart, "intensity", chart_link)]

    out += ["## Caveats", "", *[f"- {c}" for c in CAVEATS], ""]
    return "\n".join(out)


def summary(stats: Mapping[str, Any] | None, charts: Sequence[Mapping[str, Any]]) -> dict:
    tests = (stats or {}).get("tests") or []
    return {
        "factors": [t["factor"] for t in _ordered(tests)],
        "significant": [t["factor"] for t in _ordered(tests) if t.get("significant")],
        "charts": [c["name"] for c in charts],
    }


def _load(path: Path | None) -> Any:
    return None if path is None else json.loads(path.read_text())


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="railfall.analysis.writeup", description=__doc__)
    parser.add_argument("--stats", type=Path, help="weather-stats.json (analysis.weather)")
    parser.add_argument("--report", type=Path, help="weather-report.json (transform.report)")
    parser.add_argument("--charts", type=Path, help="charts.json manifest (analysis.charts)")
    parser.add_argument("--out", type=Path, default=Path("docs/RESULTS.md"))
    parser.add_argument("--summary", type=Path, help="also write a JSON summary here")
    parser.add_argument(
        "--check", action="store_true", help="fail if --out differs instead of writing it"
    )
    args = parser.parse_args(argv)
    if args.stats is None and args.report is None:
        parser.error("give --stats and/or --report")

    stats = _load(args.stats)
    manifest = (_load(args.charts) or {}).get("charts", [])
    link = "."
    if args.charts is not None:
        rel = os.path.relpath(args.charts.parent.resolve(), args.out.parent.resolve())
        link = Path(rel).as_posix()
    text = render(stats, _load(args.report), manifest, chart_link=link)

    if args.summary is not None:
        args.summary.write_text(json.dumps(summary(stats, manifest), indent=2) + "\n")
    if args.check:
        current = args.out.read_text() if args.out.exists() else ""
        if current != text:
            print(f"error: {args.out} is out of date; run `make results`", file=sys.stderr)
            return 1
        print(f"{args.out}: up to date")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(f"{args.out}: written ({len(text.splitlines())} lines)")
    if stats is not None and not stats.get("ok", True):
        print("error: the significance tests reported errors", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
